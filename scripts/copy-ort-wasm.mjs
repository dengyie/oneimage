// Copies the onnxruntime-web runtime assets into a VERSIONED directory under
// public/models/ort/<version>/ and writes the version constant the worker
// imports. Versioned URLs make every ORT upgrade a cache-busting path change
// and keep a browser's stale pre-fix entries unreachable. Runs before
// build/dev; the files are not committed.
import { mkdirSync, copyFileSync, writeFileSync, readFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(fileURLToPath(import.meta.url))
const pkg = JSON.parse(readFileSync(join(root, '..', 'node_modules', 'onnxruntime-web', 'package.json'), 'utf8'))
const version = pkg.version
const distDir = join(root, '..', 'node_modules', 'onnxruntime-web', 'dist')
const outDir = join(root, '..', 'public', 'models', 'ort', version)
mkdirSync(outDir, { recursive: true })

const required = [
  'ort.bundle.min.mjs',
  'ort-wasm-simd-threaded.mjs',
  'ort-wasm-simd-threaded.jsep.mjs',
  'ort-wasm-simd-threaded.wasm',
  'ort-wasm-simd-threaded.jsep.wasm',
]
for (const name of required) {
  copyFileSync(join(distDir, name), join(outDir, name))
}

const constFile = join(root, '..', 'src', 'infrastructure', 'inpaint', 'ort-version.ts')
writeFileSync(
  constFile,
  `// Generated by scripts/copy-ort-wasm.mjs — do not edit.\nexport const ORT_VERSION = '${version}'\n`
)
console.log(`copy-ort-wasm: ${required.length} assets -> public/models/ort/${version}/`)
